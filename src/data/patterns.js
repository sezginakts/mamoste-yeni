// Tüm cümleleri tek listede döndüren yardımcı (id → cümle eşlemesi için).
export const ALL_SENTENCES = PATTERNS.flatMap((p) =>
  p.sentences.map((s) => ({ ...s, patternId: p.id, patternColor: p.color, patternName: p.name }))
);

export const SENTENCE_BY_ID = Object.fromEntries(ALL_SENTENCES.map((s) => [s.id, s]));

export const PATTERN_BY_ID = Object.fromEntries(PATTERNS.map((p) => [p.id, p]));

// Bir kategorinin kalıp objelerini sıraya göre döndürür.
export function patternsOfCategory(categoryId) {
  const cat = CATEGORIES.find((c) => c.id === categoryId);
  if (!cat) return [];
  return cat.patternIds.map((pid) => PATTERN_BY_ID[pid]).filter(Boolean);
}
